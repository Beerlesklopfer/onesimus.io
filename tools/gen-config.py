#!/usr/bin/env python3
"""Generate the configuration reference of onesimus.io (content/docs/config/).

Source, in this order of preference:
  --grammar FILE   odir's console grammar (.grammar JSON), once odir carries the
                   directive texts: the `configure add <type>` arguments with
                   their `long` texts and examples. Resource types that have no
                   texts in the grammar yet fall back to the data directory.
  --data DIR       data/config/*.json (default), the hand-over format described
                   in tools/README.md.

Deterministic output; generated pages carry a marker and pages of resource
types that disappeared are removed. Python 3 standard library only.
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mdutil import md, md_cell, code, code_block, yaml_str, first_sentence  # noqa: E402

MARKER = "generated by tools/gen-config.py"
HEADER = ("<!-- %s from data/config/*.json (or the Director's .grammar). Do not edit by hand. -->"
          % MARKER)
ORDER = ["director", "client", "storage", "catalog", "job", "jobdefs", "fileset", "schedule", "pool",
         "messages", "counter", "profile", "console", "user"]


def anchor(key):
    return "d-" + re.sub(r"[^a-z0-9_-]+", "-", key.lower())


def block_anchor(block, key):
    return "b-%s-%s" % (re.sub(r"[^a-z0-9]+", "-", block.lower()), re.sub(r"[^a-z0-9_-]+", "-", key.lower()))


# --------------------------------------------------------------------------
# sources


def load_data(path):
    docs = {}
    for name in sorted(os.listdir(path)):
        if name.endswith(".json"):
            with open(os.path.join(path, name), encoding="utf-8") as f:
                doc = json.load(f)
            docs[doc["key"]] = doc
    return docs


def load_grammar(path, fallback):
    """Directive texts from the grammar (configure add <type>); a type whose
    arguments still carry placeholder descriptions keeps the data file."""
    with open(path, encoding="utf-8") as f:
        g = json.load(f)
    g = g.get("grammar", g)
    conf = next((c for c in g["commands"] if c["word"] == "configure"), None)
    add = next((s for s in (conf or {}).get("subs", []) if s["word"] == "add"), None)
    docs = dict(fallback)
    for t in (add or {}).get("subs", []):
        args = t.get("args", [])
        if not args or all(a.get("description", "").startswith("Directive (") for a in args):
            continue
        base = fallback.get(t["word"], {})
        by_key = {d["key"]: d for d in base.get("directives", [])}
        dirs = []
        for a in args:
            old = by_key.get(a["name"], {})
            dirs.append({
                "name": old.get("name", a["name"]), "key": a["name"], "aliases": old.get("aliases", []),
                "type": a.get("type", old.get("type", "")), "default": a.get("default", old.get("default")),
                "values": a.get("values", old.get("values", [])), "required": a.get("required", False),
                "deprecated": old.get("deprecated", False), "onesimus": old.get("onesimus", False),
                "description": " ".join(a.get("long", [])) or a.get("description", ""),
                "examples": [{"console": e["line"], "explanation": e.get("explanation", "")}
                             for e in a.get("examples", [])] or old.get("examples", []),
            })
        docs[t["word"]] = dict(base, directives=dirs, key=t["word"],
                               resource=base.get("resource", t["word"].capitalize()))
    return docs


# --------------------------------------------------------------------------
# rendering

UNITS = [(365 * 86400, "year"), (30 * 86400, "month"), (7 * 86400, "week"), (86400, "day"),
         (3600, "hour"), (60, "minute")]


def human_default(d):
    v = d.get("default")
    if v is None or v == "":
        return ""
    if d.get("type") == "time" and re.fullmatch(r"\d+", str(v)) and int(v) > 0:
        n = int(v)
        for size, unit in UNITS:
            if n % size == 0:
                k = n // size
                return "%s (%d %s%s)" % (code(str(v), True), k, unit, "" if k == 1 else "s")
    return code(str(v), True)


def flags(d):
    f = []
    if d.get("required"):
        f.append("required")
    if d.get("deprecated"):
        f.append("deprecated")
    if d.get("onesimus"):
        f.append("Onesimus")
    return ", ".join(f)


def directive_section(d, level, anchor_id):
    parts = ["%s %s {#%s}" % ("#" * level, md(d["name"]), anchor_id)]
    meta = ["Key: %s" % code(d["key"]), "Type: %s" % md(d.get("type", ""))]
    if d.get("default") not in (None, ""):
        meta.append("Default: %s" % human_default(d).replace("\\|", "|"))
    if d.get("values"):
        meta.append("Values: " + ", ".join(code(v) for v in d["values"]))
    if d.get("aliases"):
        meta.append("Aliases: " + ", ".join(md(a) for a in d["aliases"]))
    fl = flags(d)
    if fl:
        meta.append(md(fl.capitalize()))
    parts.append(" · ".join(meta))
    if d.get("description"):
        parts.append(md(d["description"]))
    for ex in d.get("examples", []):
        if ex.get("explanation"):
            parts.append(md(ex["explanation"]))
        if ex.get("config"):
            parts.append(code_block(ex["config"].split("\n")))
        if ex.get("console"):
            parts.append("In the console:")
            parts.append(code_block([ex["console"]]))
    return "\n\n".join(parts)


def overview(dirs, anchor_fn):
    rows = ["| Directive | Type | Default | | Summary |", "|---|---|---|---|---|"]
    for d in dirs:
        rows.append("| [%s](#%s) | %s | %s | %s | %s |" % (
            md_cell(d["name"]), anchor_fn(d), md_cell(d.get("type", "")), human_default(d),
            md_cell(flags(d)), md_cell(first_sentence(d.get("description", "")))))
    return "\n".join(rows)


def page(doc, weight):
    title = doc["resource"]
    fm = ["---", "title: %s" % yaml_str(title + " resource"),
          "description: %s" % yaml_str(first_sentence(doc.get("description", ""))),
          "weight: %d" % weight, "---", "", HEADER, ""]
    body = [md(doc.get("description", ""))]
    if doc.get("examples"):
        body.append("## Examples")
        for ex in doc["examples"]:
            body.append("**%s**" % md(ex["title"]))
            body.append(code_block(ex["config"].split("\n")))
            if ex.get("explanation"):
                body.append(md(ex["explanation"]))
    dirs = doc.get("directives", [])
    body.append("## Directives")
    body.append(overview(dirs, lambda d: anchor(d["key"])))
    for d in dirs:
        body.append(directive_section(d, 3, anchor(d["key"])))
    for b in doc.get("blocks", []):
        body.append("## %s block {#block-%s}" % (md(b["name"]), re.sub(r"[^a-z0-9]+", "-", b["key"])))
        if b.get("description"):
            body.append(md(b["description"]))
        body.append(overview(b["directives"], lambda d, b=b: block_anchor(b["key"], d["key"])))
        for d in b["directives"]:
            body.append(directive_section(d, 3, block_anchor(b["key"], d["key"])))
    body.append("See also: [configuration reference](../), [`configure`](/docs/commands/configure/), "
                "[`show`](/docs/commands/show/)")
    return "\n".join(fm) + "\n" + "\n\n".join(body) + "\n"


def index(docs):
    fm = ["---", 'title: "Configuration reference"',
          'description: "Every directive of the Director configuration: meaning, defaults, pitfalls and '
          'examples, with the Onesimus extensions."', "weight: 35", "---", "", HEADER, ""]
    body = ["The Onesimus Director reads the configuration of the Bareos 25 Director: the same resources, "
            "directives and syntax in the same files. Directives marked *Onesimus* exist only in the "
            "Onesimus Director. Most directives can also be changed from the console with "
            "[`configure`](/docs/commands/configure/) or in the Onesimus GUI.",
            "Syntax in brief: a resource is `Type { ... }`, a directive is `Name = value`; names are "
            "case-insensitive and spaces in them do not matter (`Maximum Concurrent Jobs` and "
            "`MaximumConcurrentJobs` are the same, the console writes `maximumconcurrentjobs`). Strings "
            "with spaces go in double quotes, # starts a comment, and `@file` includes another file.",
            "| Resource | Directives | Description |", "|---|---|---|"]
    rows = []
    for key in ORDER:
        if key in docs:
            d = docs[key]
            rows.append("| [%s](%s/) | %d | %s |" % (md_cell(d["resource"]), key, len(d.get("directives", [])),
                                                     md_cell(first_sentence(d.get("description", "")))))
    text = "\n\n".join(body[:2]) + "\n\n" + "\n".join(body[2:] + rows)
    return "\n".join(fm) + "\n" + text + "\n"


def write(path, text, written):
    written.add(os.path.abspath(path))
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return 1
    return 0


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", default=os.path.join(here, "..", "data", "config"))
    ap.add_argument("--grammar")
    ap.add_argument("--out", default=os.path.join(here, "..", "content", "docs", "config"))
    opt = ap.parse_args()
    docs = load_data(opt.data)
    if opt.grammar:
        docs = load_grammar(opt.grammar, docs)
    os.makedirs(opt.out, exist_ok=True)
    written = set()
    changed = 0
    keys = [k for k in ORDER if k in docs] + sorted(k for k in docs if k not in ORDER)
    for i, key in enumerate(keys, start=1):
        changed += write(os.path.join(opt.out, key + ".md"), page(docs[key], i), written)
    changed += write(os.path.join(opt.out, "_index.md"), index(docs), written)
    removed = 0
    for name in sorted(os.listdir(opt.out)):
        p = os.path.abspath(os.path.join(opt.out, name))
        if name.endswith(".md") and not name.endswith(".de.md") and p not in written:
            with open(p, encoding="utf-8") as f:
                if MARKER in f.read(2048):
                    os.remove(p)
                    removed += 1
    print("%d resource types, %d files changed, %d removed" % (len(keys), changed, removed))


if __name__ == "__main__":
    main()
