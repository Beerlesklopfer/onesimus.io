#!/usr/bin/env python3
"""Generate the console command reference of onesimus.io from the console grammar.

The grammar is what the Onesimus Director prints for `.grammar` in API mode 2
(`{"grammar": {"schema": 1, "commands": [...]}}`). The script writes
content/docs/commands/_index.md and one page per top-level command. Output is
deterministic: running it twice on the same grammar gives identical files, and
pages of commands that disappeared from the grammar are removed.

Usage: tools/gen-commands.py [grammar.json] [--out content/docs/commands]
Python 3 standard library only.
"""

import argparse
import html
import json
import os
import re
import sys

DEFAULT_GRAMMAR = os.path.expanduser("~/.cache/onesimus-agents/website/console-grammar.json")
MARKER = "generated by tools/gen-commands.py"
HEADER = ("<!-- %s from the console grammar (.grammar). Do not edit by hand: "
          "change the grammar in the Director and regenerate. -->" % MARKER)
WRAP = 78

# --------------------------------------------------------------------------
# escaping


def md(text):
    """Escape prose for Markdown. Raw HTML is enabled on the site, so < and > must
    become entities; '{{<' and '{{%' would start a Hugo shortcode."""
    text = text.replace("\\", "\\\\")
    text = html.escape(text, quote=False)
    for ch in "`*_[]":
        text = text.replace(ch, "\\" + ch)
    text = text.replace("{{", "{&#123;")
    # A paragraph must not turn into a heading, list or quote.
    text = re.sub(r"^(\s*)([#+\-=>]|\d+[.)])", lambda m: m.group(1) + "\\" + m.group(2), text)
    return text


def md_cell(text):
    """Prose inside a table cell."""
    return md(text).replace("|", "\\|").replace("\n", " ")


def code(text, in_table=False):
    """An inline code span. Backslash-escaping does not work in code spans, but a
    GFM table needs \\| even there; '{{<' is broken up with a zero-width joiner
    would change the text, so such spans fall back to <code>."""
    if "{{<" in text or "{{%" in text:
        out = "<code>%s</code>" % html.escape(text).replace("{", "&#123;")
    else:
        fence = "``" if "`" in text else "`"
        pad = " " if text.startswith("`") or text.endswith("`") else ""
        out = fence + pad + text + pad + fence
    if in_table:
        out = out.replace("|", "\\|")
    return out


def code_block(lines):
    """A code block. Fenced unless the text contains shortcode delimiters, which
    Hugo would expand even inside a fence."""
    body = "\n".join(lines)
    if "{{<" in body or "{{%" in body:
        esc = html.escape(body).replace("{", "&#123;")
        return '<pre class="synopsis"><code>%s</code></pre>' % esc
    return "```text\n%s\n```" % body


def yaml_str(text):
    # JSON strings are valid YAML double-quoted scalars.
    return json.dumps(text, ensure_ascii=False)


def sentence(text):
    text = text.strip()
    if not text:
        return text
    text = text[0].upper() + text[1:]
    if text[-1] not in ".!?:":
        text += "."
    return text


# --------------------------------------------------------------------------
# names and links


def page_name(word):
    """File name like the man pages: '.acl' -> 'dot-acl', '.' -> 'dot'."""
    if word == ".":
        return "dot"
    if word.startswith("."):
        return "dot-" + word[1:]
    return word


def anchor(path):
    """Explicit heading id for a subcommand path (list of words)."""
    slug = "-".join(re.sub(r"[^a-z0-9_]+", "-", w.lower()).strip("-") or "dot" for w in path)
    return "sub-" + slug


class Index:
    def __init__(self, commands):
        self.by_word = {}
        for c in commands:
            self.by_word[c["word"]] = c["word"]
        for c in commands:
            for a in c.get("aliases", []):
                self.by_word.setdefault(a, c["word"])
        self.missing = set()

    def resolve(self, word):
        return self.by_word.get(word)

    def link(self, word, rel="../", in_table=False):
        target = self.resolve(word)
        if target is None:
            self.missing.add(word)
            return code(word, in_table)
        return "[%s](%s%s/)" % (code(word, in_table), rel, page_name(target))


# --------------------------------------------------------------------------
# synopsis


def placeholder(arg):
    vals = arg.get("values") or []
    if arg.get("type") in ("enum", "bool") and vals and len(vals) <= 4 and \
            sum(len(v) for v in vals) <= 30:
        return "<%s>" % "|".join(vals)
    return "<%s>" % arg["name"]


def arg_token(arg):
    """One argument in Bareos usage style, without the optional brackets."""
    name = arg["name"]
    if arg.get("positional"):
        vals = arg.get("values") or []
        if vals and arg.get("type") == "enum":
            tok = " | ".join(vals)
        else:
            tok = "<%s>" % name
    elif arg.get("kind") == "keyword":
        tok = name
    else:
        ph = placeholder(arg)
        if arg.get("list"):
            ph += "[,...]"
        tok = "%s[=%s]" % (name, ph) if arg.get("value_optional") else "%s=%s" % (name, ph)
    if arg.get("repeatable"):
        tok += " ..."
    return tok


def arg_items(args):
    """Synopsis items for a list of arguments; members of one group are joined
    into one alternative. Optional items get brackets."""
    items = []
    seen_groups = {}
    for arg in args:
        group = arg.get("group")
        if group:
            if group in seen_groups:
                seen_groups[group].append(arg)
                continue
            members = [arg]
            seen_groups[group] = members
            items.append(("group", members))
        else:
            items.append(("arg", arg))
    out = []
    for kind, item in items:
        if kind == "group":
            alts = " | ".join(arg_token(a) for a in item)
            if any(a.get("required") for a in item):
                out.append("(%s)" % alts if len(item) > 1 else alts)
            else:
                out.append("[%s]" % alts)
        else:
            tok = arg_token(item)
            positional_alt = item.get("positional") and " | " in tok
            if item.get("required"):
                out.append("(%s)" % tok if positional_alt else tok)
            else:
                out.append("[%s]" % tok)
    return out


def path_tokens(chain):
    """The command words of a node chain, with a subcommand's own value."""
    toks = []
    for node in chain:
        word = node["word"]
        val = node.get("value")
        if val:
            ph = "<%s>" % val["name"]
            if val.get("list"):
                ph += "[,...]"
            word = "%s[=%s]" % (word, ph) if val.get("value_optional") else "%s=%s" % (word, ph)
        toks.append(word)
    return toks


def effective_args(chain):
    """Arguments of a node plus the inherited ones of its ancestors (outermost
    first). An argument named like the node's own value is that value again."""
    args = []
    names = set()
    for node in chain:
        for a in node.get("args", []):
            if a["name"] in names:
                continue
            names.add(a["name"])
            args.append(a)
    last = chain[-1]
    if last.get("value"):
        args = [a for a in args if a["name"] != last["value"]["name"] or a.get("positional")]
    return args


def wrap_line(head, items):
    """Wrap a synopsis line; continuation lines are indented under the first argument."""
    indent = " " * min(len(head) + 1, 24)
    lines = []
    cur = head
    for it in items:
        if len(cur) + 1 + len(it) > WRAP and cur.strip() != head.strip() and cur.strip():
            lines.append(cur)
            cur = indent + it
        else:
            cur = cur + " " + it
    lines.append(cur)
    return lines


def synopsis_lines(chain):
    head = " ".join(path_tokens(chain))
    items = arg_items(effective_args(chain))
    if chain[-1].get("free_text") and not any(a.get("positional") for a in effective_args(chain)):
        items.append("[<text> ...]")
    return wrap_line(head, items)


def invocable(chain):
    """A node with subcommands is a command of its own when one of its examples
    uses it without a subcommand ('purge', 'status', 'show client=x')."""
    node = chain[-1]
    if not node.get("subs"):
        return True
    words = set()
    for s in node["subs"]:
        words.add(s["word"])
        words.update(s.get("aliases", []))
    depth = len(chain)
    for ex in node.get("examples", []):
        toks = ex["line"].split()
        if len(toks) < depth:
            continue
        if len(toks) == depth or toks[depth].split("=", 1)[0] not in words:
            return True
    return False


def leaves(chain):
    """Every node chain that is a complete command line, in tree order."""
    node = chain[-1]
    if invocable(chain):
        yield chain
    for s in node.get("subs", []):
        yield from leaves(chain + [s])


# --------------------------------------------------------------------------
# page parts


def origin_of(chain):
    """A subcommand of an Onesimus command is an Onesimus extension too."""
    for node in chain:
        if node.get("origin") == "onesimus":
            return "onesimus"
    return "bareos"


def has_extension(node):
    if node.get("origin") == "onesimus":
        return True
    return any(has_extension(s) for s in node.get("subs", []))


def badge(origin, partial=False):
    if origin == "onesimus":
        return '<span class="origin-badge origin-badge--onesimus">Onesimus extension</span>'
    if partial:
        return ('<span class="origin-badge origin-badge--bareos">Bareos</span> '
                '<span class="origin-badge origin-badge--onesimus">with Onesimus extensions</span>')
    return '<span class="origin-badge origin-badge--bareos">Bareos</span>'


def origin_label(node):
    if node.get("origin") == "onesimus":
        return "Onesimus extension"
    if has_extension(node):
        return "Bareos, with Onesimus extensions"
    return "Bareos"


def flags(arg):
    f = []
    if arg.get("required"):
        f.append("required")
    if arg.get("repeatable"):
        f.append("repeatable")
    if arg.get("list"):
        f.append("list")
    if arg.get("positional"):
        f.append("positional")
    if arg.get("value_optional"):
        f.append("value optional")
    if arg.get("group"):
        f.append("one of: %s" % arg["group"])
    return ", ".join(f)


def values_cell(arg, idx):
    vals = arg.get("values") or []
    if vals:
        return ", ".join(code(v, True) for v in vals)
    src = arg.get("source")
    if src:
        if src == "@commands":
            return "command names"
        return "from " + idx.link(src, in_table=True)
    return ""


def arg_table(args, idx):
    rows = ["| Argument | Type | Values / source | Default | Flags | Description |",
            "|---|---|---|---|---|---|"]
    for a in args:
        if a.get("positional"):
            name = "<%s>" % a["name"]
        elif a.get("kind") == "keyword":
            name = a["name"]
        else:
            name = a["name"] + "="
        typ = "keyword" if a.get("kind") == "keyword" else a.get("type", "")
        default = code(str(a["default"]), True) if "default" in a and a["default"] is not None else ""
        rows.append("| %s | %s | %s | %s | %s | %s |" % (
            code(name, True), md_cell(typ), values_cell(a, idx), default,
            md_cell(flags(a)), md_cell(sentence(a.get("description", "")))))
    return "\n".join(rows)


def examples_md(examples):
    out = []
    for ex in examples:
        expl = sentence(ex.get("explanation", ""))
        if expl:
            out.append(md(expl.rstrip(".") + ":"))
        out.append(code_block([ex["line"]]))
    return "\n\n".join(out)


def subsection(chain, idx, level):
    node = chain[-1]
    path = [n["word"] for n in chain]
    title = " ".join(path)
    parts = []
    tag = ""
    if origin_of(chain) == "onesimus" and origin_of(chain[:-1]) != "onesimus":
        tag = " " + badge("onesimus")
    parts.append("%s %s {#%s}" % ("#" * level, md(title), anchor(path)))
    if tag:
        parts.append(tag.strip())
    if node.get("description"):
        parts.append("**%s**" % md(sentence(node["description"])))
    if node.get("aliases"):
        parts.append("Aliases: " + ", ".join(code(a) for a in node["aliases"]))
    for p in node.get("long", []):
        parts.append(md(p))
    if not node.get("subs"):
        parts.append(code_block(synopsis_lines(chain)))
    else:
        lines = []
        for leaf in leaves(chain):
            lines.extend(synopsis_lines(leaf))
        parts.append(code_block(lines))
    own = list(node.get("args", []))
    if node.get("value"):
        own = [node["value"]] + own
    if own:
        parts.append(arg_table(own, idx))
    inherited = []
    for anc_i in range(len(chain) - 1):
        anc = chain[anc_i]
        if anc.get("args"):
            names = ", ".join(code(a["name"]) for a in anc["args"])
            target = "#arguments" if anc_i == 0 else "#" + anchor([n["word"] for n in chain[:anc_i + 1]])
            inherited.append("[%s](%s): %s" % (md(" ".join(n["word"] for n in chain[:anc_i + 1])),
                                               target, names))
    if inherited:
        parts.append("Also accepts the arguments of " + "; ".join(inherited) + ".")
    if node.get("examples"):
        parts.append(examples_md(node["examples"]))
    if node.get("see_also"):
        parts.append("See also: " + ", ".join(idx.link(s) for s in node["see_also"]))
    out = ["\n\n".join(parts)]
    for s in node.get("subs", []):
        out.append(subsection(chain + [s], idx, min(level + 1, 6)))
    return "\n\n".join(out)


def command_page(cmd, weight, idx):
    word = cmd["word"]
    fm = ["---",
          "title: %s" % yaml_str(word),
          "description: %s" % yaml_str(sentence(cmd.get("description", ""))),
          "weight: %d" % weight,
          "---", "", HEADER, ""]
    body = []
    body.append(badge(cmd.get("origin"), partial=has_extension(cmd) and cmd.get("origin") != "onesimus"))
    body.append(md(sentence(cmd.get("description", ""))))
    if cmd.get("aliases"):
        body.append("Aliases: " + ", ".join(code(a) for a in cmd["aliases"]))

    body.append("## Synopsis")
    lines = []
    for leaf in leaves([cmd]):
        lines.extend(synopsis_lines(leaf))
    body.append(code_block(lines))
    body.append("Words without brackets are required, `[ ]` marks optional parts, "
                "`a | b` alternatives, `...` a repeatable argument and `[,...]` a comma separated list.")

    body.append("## Description")
    for p in cmd.get("long", []):
        body.append(md(p))

    if cmd.get("args") or cmd.get("value"):
        body.append("## Arguments {#arguments}")
        own = list(cmd.get("args", []))
        body.append(arg_table(own, idx))
        if cmd.get("subs"):
            body.append("These arguments apply to every subcommand as well.")

    if cmd.get("subs"):
        body.append("## Subcommands")
        for s in cmd["subs"]:
            body.append(subsection([cmd, s], idx, 3))

    if cmd.get("examples"):
        body.append("## Examples")
        body.append(examples_md(cmd["examples"]))

    see = [idx.link(s) for s in cmd.get("see_also", [])]
    body.append("## See also")
    body.append(", ".join(see + ["[Command reference](../)"]))
    return "\n".join(fm) + "\n" + "\n\n".join(body) + "\n"


def sort_key(cmd):
    return cmd["word"].lstrip(".").lower(), cmd["word"]


def index_page(regular, dots, idx):
    fm = ["---",
          'title: "Command reference"',
          'description: "Every console command of the Onesimus Director: synopsis, arguments, '
          'examples, and which commands extend Bareos."',
          "weight: 30",
          "---", "", HEADER, ""]
    body = [
        "The Onesimus Director (`odir`) speaks the console language of the Bareos Director. "
        "Every Bareos command works the same way in `oconsole`, in `bconsole` and in the "
        "Onesimus GUI. Commands and arguments marked *Onesimus extension* exist only in the "
        "Onesimus Director.",
        "This reference is generated from the console grammar that the Director itself "
        "prints with `.grammar`; the same grammar drives completion and help in the console. "
        "Dot commands are meant for programs such as the GUI, but you can type them as well.",
        "## Regular commands",
        "| Command | Description | Origin |",
        "|---|---|---|",
    ]
    table = body
    for c in regular:
        table.append("| %s | %s | %s |" % (idx.link(c["word"], rel="", in_table=True),
                                           md_cell(sentence(c.get("description", ""))),
                                           md_cell(origin_label(c))))
    body.append("")
    body.append("## Dot commands")
    body.append("| Command | Description | Origin |")
    body.append("|---|---|---|")
    for c in dots:
        table.append("| %s | %s | %s |" % (idx.link(c["word"], rel="", in_table=True),
                                           md_cell(sentence(c.get("description", ""))),
                                           md_cell(origin_label(c))))
    # Tables must stay contiguous, so join the table rows with single newlines.
    out = []
    buf = []
    for line in body:
        if line.startswith("|"):
            buf.append(line)
            continue
        if buf:
            out.append("\n".join(buf))
            buf = []
        if line:
            out.append(line)
    if buf:
        out.append("\n".join(buf))
    return "\n".join(fm) + "\n" + "\n\n".join(out) + "\n"


def write(path, text, written):
    written.add(os.path.abspath(path))
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return True
    return False


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("grammar", nargs="?", default=DEFAULT_GRAMMAR)
    ap.add_argument("--out", default=os.path.join(here, "..", "content", "docs", "commands"))
    opt = ap.parse_args()

    with open(opt.grammar, encoding="utf-8") as f:
        data = json.load(f)
    grammar = data.get("grammar", data)
    if grammar.get("schema") != 1:
        sys.exit("unsupported grammar schema %r" % grammar.get("schema"))
    commands = grammar["commands"]
    idx = Index(commands)

    regular = sorted((c for c in commands if not c.get("dot")), key=sort_key)
    dots = sorted((c for c in commands if c.get("dot")), key=sort_key)

    os.makedirs(opt.out, exist_ok=True)
    written = set()
    changed = 0
    for weight, c in enumerate(regular, start=1):
        changed += write(os.path.join(opt.out, page_name(c["word"]) + ".md"),
                         command_page(c, weight, idx), written)
    for weight, c in enumerate(dots, start=1001):
        changed += write(os.path.join(opt.out, page_name(c["word"]) + ".md"),
                         command_page(c, weight, idx), written)
    changed += write(os.path.join(opt.out, "_index.md"), index_page(regular, dots, idx), written)

    # Remove pages of commands that left the grammar (only our own files).
    removed = 0
    for name in sorted(os.listdir(opt.out)):
        p = os.path.abspath(os.path.join(opt.out, name))
        if not name.endswith(".md") or name.endswith(".de.md") or p in written:
            continue
        with open(p, encoding="utf-8") as f:
            if MARKER in f.read(2048):
                os.remove(p)
                removed += 1

    print("%d commands, %d files changed, %d removed" % (len(commands), changed, removed))
    for w in sorted(idx.missing):
        if w != "@commands":
            print("warning: reference to unknown command %r" % w, file=sys.stderr)


if __name__ == "__main__":
    main()
